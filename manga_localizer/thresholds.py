"""跨路径共用的阈值与补偿量。

Photos 蓝框路径与 Paddle 检测路径**必须共用同一套规则**，这些数字此前各写
一份（`one_click_translate.py` 与 `photos_capture.py` 各有一个 0.20），存在
"规则应当相同、实际各自漂移"的隐患。集中到这里，两边 import 同一份。

集中后两条路径的差异只剩"框从哪来、框多松"，规则本身不再分叉。
"""

from __future__ import annotations

# --- 共用规则 ---------------------------------------------------------------

# 整页大框过滤：框面积 > 该比例 × 页面积 → 丢弃（不是原子文字单位）
WHOLE_PAGE_AREA_RATIO = 0.20

# 大拟音/效果字过滤：框短边 > 该比值 × 同方向基准（横比横、竖比竖；
# 同方向样本 <3 时回落全页基准）且 > 页短边 × 该比例 → 丢弃。
# **同一个倍数还驱动"过大单框字号封顶"**（未合并的单框超这个倍数就按拟声词
# 封顶字号）。用户实书反馈后由 2.0 调到 1.5。
SFX_MIN_SIDE_RATIO = 1.5
SFX_MIN_SIDE_PAGE = 0.10

# 拟声词自动进术语库的门槛：同一原文 + 同一译法至少出现 N 次才收录
# （见 manga_localizer/glossary_auto.py）。0 = 关闭自动收录。
SFX_GLOSSARY_MIN_COUNT = 2

# --- 手绘字（画在画面上的效果字/拟声词）过滤 ---------------------------------
# **默认关**（`--drop-art-boxes` 才开）。
#
# 判据 = 「岛底不像气泡」+「字数很短（或竖排且更不像气泡）」。三个数字都由实书
# 逐条人工判定（324 个岛）扫出来的，见 开发记录「手绘字过滤·闸门标定」：
#
# `ART_TEXT_FLAT_RATIO`（0.70）= 取样矩形内"局部平坦"像素占比的上限。
#   比它更低 → 这个岛的底不是气泡/平坦底，是画面 → 手绘字候选。
#   **0.70 而不是 0.40**：0.40 会把"底色没那么深"的手绘拟声整段放过
#   （实测 どきっ 0.40 / ずまごめ 0.45 / キェツ♡ 0.52 / ゴゴゴ 0.63 全在中间带）。
#   上限可以这么松，是因为**气泡对白的占比实测 ≥ 0.74**（んっ♡ 0.89 / は～♡ 0.82 /
#   あ〜♡ 0.80…），两者之间有空档。扫参实测（同一批 324 条真值）：
#     闸门 0.40 → 召回 83.6%；0.50 → 90.3%；0.60 → 93.3%；**0.70 → 94.5%**；
#     0.75 → 94.5%（误伤翻三倍）；0.80 → 95.2%（误伤 17）。取拐点 0.70。
ART_TEXT_FLAT_RATIO = 0.70

# 取样矩形 = **成员框原样并集** ± 该值（判据量的是这一块）。
# 注意**不能用岛的 `image_bbox`**：那个带着编组扩边 6px，而扩边是给填黑/擦字/
# 嵌字用的版面余量（见 `_group_boxes_by_overlap` 的 docstring），不是文字范围；
# 拿它当取样框会把邻居的墨迹一起吃进来（实测页 6「えーと」被邻居压掉 30% 面积，
# 占比被拉到 0.60）。
ART_TEXT_PAD = 2

# 「局部平坦」判据：3×3 邻域的亮度极差 < 该值即视为平坦。网点/线条的极差远
# 大于此，白底与纯色块的极差为 0。
ART_TEXT_FLAT_RANGE = 24

# 手绘字的字数上限（非空白字符）：手绘效果字都很短，压在画面上的印刷正文
# （封面警示语、后记段落）都在这之上。
#
# **但竖排岛在这个占比以下时可以无视字数护栏**（`ART_TEXT_VERTICAL_RATIO`）：
# 长拟声词确实存在（实测 `びくっぷるぷるふるふるえる`、`ぬるっと♡じゅっ必ずい`、
# `だいすき♡はあと♡ちゅっ♡`，占比只有 0.15~0.37 却被 10 字护栏放过）。它们和
# "压在画面上的印刷正文"的区别是**排版方向**：封面警示语/后记段落是**横排长行**，
# 手绘拟声是**竖排列**。加这一条：漏 16 → 2，误伤 3 不变。
# 扫参：豁免上限 0.30 → 漏 6；**0.40 → 漏 2**；0.50/0.60 同 0.40；0.70 → 误伤
# 3 → 10（开始碰到气泡里的大台词的边）。取 0.40。
ART_TEXT_MAX_CHARS = 10
ART_TEXT_VERTICAL_RATIO = 0.40

# 按书自标定：用这本书自己的**长文本岛**（≥ ART_TEXT_BALLOON_MIN_CHARS 字，
# 几乎必然是对白）的平坦占比自证"气泡基准"。基准可信才用几何判据。
ART_TEXT_BALLOON_MIN_CHARS = 12
# 基准必须"又高又稳"：长文本岛的 **p25** 低于此值 → 自证不住 → **整本禁用**。
#
# **用 p25 而不是 p10**（2026-09 实测纠正）：长文本岛里必然混着少数"不该算气泡
# 基准"的岛——横排印刷长文（封面警示语 0.17 / 后记段落 0.34 / 版权页）与**偶然被
# 读出 ≥12 字的手绘字**（`ぬるっと♡じゅっ必ずい` 0.15 / `[手写台词片段]` 0.14）。
# 甲书 一本在**当前编组**下 p10 = 0.67（过），换成老编组就变 0.37（不过）——
# 判据没动、只是编组变了，说明 p10 这个位置由少数污染岛决定，不该拿来当闸门。
# p25 在两个编组下都是 0.73~0.76，稳。
#
# 实测（长文本岛 p25）：
#   甲书     0.76（当前编组）/ 0.73（老编组）→ 自证得住，闸门 0.69 → 岛级 F1 0.985
#   乙书 0.56 → 自证不住，强跑精确率只有 30.9%，**禁用**（一个岛都不丢）
# 阈值的两条边距（+0.11 / −0.09）比 p10 时代（+0.07 / −0.14）健康。
ART_TEXT_BALLOON_MIN_P25 = 0.65
# 闸门 = 长文本岛占比中位数 × 该系数，再夹到 [下限, 上限]
ART_TEXT_BALLOON_RATIO = 0.90
ART_TEXT_GATE_MIN = 0.55
ART_TEXT_GATE_MAX = 0.80

# 视觉判据（自证不住的书才用）送图时的上下文边距：岛的取样矩形 ± 该值。
# 实测 ±60px 比只送框好（精确率 90.0% vs 79.2%——模型能看到"这句话在不在气泡里"）。
ART_TEXT_VISION_CONTEXT = 60

# --- 手绘字判据的逐页路由（书级自证只当先验）---------------------------------
# 上面那个书级自证是个**二选一**：整本几何、或整本视觉。实书正好各占一头
# （甲书 p25 0.76 → 整本几何、0 次调用；乙书 p25 0.56 → 整本视觉、
# 264 次调用），但**混合的书**在两态下没有位置——同一本里正片与后记/版权页/
# 彩页的性质可以完全不同。所以把判定下沉到页，书级结论只当先验：
#
# * 书级自证得住时：某页的本地证据若**反驳**书级基准 → 该页转视觉（降级）。
#   实测甲书 24 页里只有页 22 降级（后记：本地中位 0.34 vs 书级 0.77）——
#   正是"它的长文本岛其实是横排印刷正文、不是气泡"的那种页；其余 23 页照旧
#   几何、依旧 0 次调用。页 1/2 的 p25 刚好压线（0.65）但中位 0.68/0.75 与书级
#   同向，按"中位差"判就不会被这点噪声推走。
# * 书级自证不住时：某页**自己证明得住**（比书级更严）才升回几何（升级）。
#   **默认关**（ART_TEXT_PAGE_PROMOTE）。实测 乙书 这是笔不划算的买卖：
#   升级那 10 页（本地 p25 ≥ 0.65）几何 F1 0.740（误丢对白 3 / 漏拟声 16），
#   视觉 F1 0.810（误丢对白 7 / 漏 9）——几何"少丢对白"却"多漏拟声"，正是它
#   的本职工作被削弱；阈值收紧到 p25 ≥ 0.70 只剩 1 页、几何召回 0.40（视觉
#   1.00）。根因是**全书没有区分度**：该书 ratio < 0.50 那一段里也只有 68.4%
#   是"不翻译"（另外 24 个是该翻译的），不是"某几页不行"。要开请先在实书上量。
#
# 页级样本天然稀少（实测每页长文本岛中位只有 3~6 个），所以规则刻意**不对称**：
# 样本不足 → 继承书级结论（不做判断，也就不花钱）；只有明确的**反向证据**才
# 改判。这样逐页路由在书级结论正确时几乎不动行为。
ART_TEXT_PAGE_MIN_SAMPLES = 3
# 降级（主判据）：页本地长文本岛占比中位比书级中位低这么多 → 该页气泡基准不成立
ART_TEXT_PAGE_DEMOTE_MARGIN = 0.15
# 降级（混合页）：样本 ≥ 该值，且本地 **p25 比书级 p25 也低** 同一幅度，同样判该页
# 自证不住。两条判据都拿书级同统计量比、都带同一个边距——直接与绝对门槛（0.65）
# 比会被边界噪声推走：实测甲书 页 2 的 p25 = 0.649，离 0.65 只差 0.001，却会把一页
# 正常的页（中位 0.747 vs 书级 0.773）整页转给视觉。样本少时 p25 就是最小值，
# 所以这条要求更多样本。
ART_TEXT_PAGE_DEMOTE_MIN_SAMPLES = 5
# 升级：页本地 p25 ≥ 该值，且长文本岛 ≥ ART_TEXT_PAGE_PROMOTE_MIN_SAMPLES
ART_TEXT_PAGE_PROMOTE_P25 = 0.70
ART_TEXT_PAGE_PROMOTE_MIN_SAMPLES = 4
# 升级总开关。默认关（标定数据见上）；开之前请在实书上量"几何 vs 视觉"。
ART_TEXT_PAGE_PROMOTE = False

# --- 保台词：只丢"两路都同意"的岛（全自动，无人工）---------------------------
# 用户要求"保证台词不丢"。**先量到底**：七个信号都分不开"手绘台词"与"手绘拟声"——
#   几何占比（最低那一档也只有 ~70% 是"不翻译"）、裁剪图视觉判据（192 个几何候选里
#   36 个误杀只救回 8 个、还倒放 13 个明显拟声）、**整页+红框**视觉判据（救回 7 个，
#   与裁剪图同级）、日文词性/词典 fugashi（退化成"长度代理"：误杀 36→9 但漏拟声
#   47→147）、中文侧判定（F1 0.194）、deepseek 看日文原文（F1 0.264）、
#   **日文母语 instruct 模型 Sarashina2.2-3B**（F1 0.664，精确率只有 0.50：一半台词
#   被判成拟音）。根本原因：判别信号在**图上**（画在画面上 vs 印在气泡里），文本里没有。
#
# 所以"台词不丢"不做成判据，做成**档位**（甲书 实测，345 个有读数有真值的岛）：
#
#   off    = 现状：几何直接丢                     误杀台词 36 / 漏拟声 47  （F1 0.752）
#   agree  = 只丢 几何 ∧ 模型判 S/U               误杀台词 28 / 漏拟声 60  （F1 0.720）
#   strict = 再要求占比 < ART_TEXT_GUARD_RATIO    误杀台词 22 / 漏拟声 72  （F1 0.682）
#            （把 ART_TEXT_GUARD_RATIO 降到 0.20 → 误杀 8 / 漏 131）
#   "不丢任何岛" = 误杀 0 / 漏 173（等于关掉这个功能）
#
# **误杀每降一档、漏拟声就涨一档，没有拐点**——要丢的和要保的是同一种东西。
# 代价：agree/strict 需要把短岛也送一次视觉判据（甲书 约 256 次调用/本；有缓存，
# 重跑不重复花钱）；没配视觉接口时自动退回 off（并在日志里说明）。
# 默认 off = 保持现状（F1 最高）；要换档就改这一行。
ART_TEXT_DIALOGUE_GUARD = "off"
# strict 档的占比上限（越小越保台词、越多拟声混入）
ART_TEXT_GUARD_RATIO = 0.40

# 整页字号上限：译文字号 ≤ 该倍数 × 该页"常规字号"（= 该页蓝框短边中位数，
# 即页面主体文字的尺寸）。每个岛各自"尽可能撑满"会让同一页出现 2 倍级差
# （实测页 7：14 字合并组 131px vs 该页基准 66px，= 2.0×），观感极不统一。
# 0 = 关闭；只封顶不放大。
PAGE_FONT_CEILING_RATIO = 1.5

# 短原文字数门槛：原文（日文，非空白字符）≤ 该值时字号封顶到 SFX_MAX_FONT_SIZE。
# **默认 0 = 关闭**：实测按"≤6 字就压到 30px"会让 127 个岛面积比掉到 0.02~0.06
# （短原文的框往往就是大的——原文那几个字本身写得大，字号跟框走才对），
# 属于"看起来更糟"的规则。留成可调参数，等确认语义后再定默认值。
SHORT_SOURCE_MAX_CHARS = 0

# 拟声词字号上限：识别准确的拟声词（短假名/符号）嵌字时字号不超过该值。
# 原因：拟声框在原图里往往又大又粗，字号跟着框走会得到一个 60~120px 的
# 巨型中文拟声，压过对白、破坏版面层次。上限把拟声固定在"小注音"的量级；
# 框小的时候仍按框自适应（取 min(框, 上限)），不会放大。
SFX_MAX_FONT_SIZE = 30

# --- 按框来源的补偿量 -------------------------------------------------------
# Photos 蓝框是"文本选区"，紧贴笔画；Paddle 检测框是"文本行 + 余量"，约松
# 2px/边。两者用同一套嵌字规则，靠这两个补偿量把观感拉平。

# 布局边界 = 擦字范围 = 成员框并集 ±该值（canonical box）。
# **现为 0**：容器就是"各成员框扩 6px（填黑/OCR 用的那层扩框）后的外接矩形"，
# 岛框与组框都不再额外扩（用户指令："那就只扩框，取外接矩形，岛和组不再扩"）。
# 保留这个入口是为了将来真要按来源微调时有地方调，而不是散在各处。
BBOX_PAD = {"paddle": 0, "photos": 0}
# 字号上限 = 组内最窄框 + 该值
GLYPH_MARGIN = {"paddle": 5, "photos": 12}

# 描边溢出余量：文字描边是**向外**画的（PIL stroke_width = 字号//10，最大约
# 6px），而块是按字身框贴边排的 —— 所以最外圈描边必然伸到布局框之外。若不
# 放宽，它会被"岛外零改动"的硬裁剪切掉（表现：边缘的字缺一笔）。
# 做法：**擦字范围与裁剪掩膜都按该余量放宽**，描边落在已擦除的区域内，原图
# 像素不被覆盖。字号越大描边越粗，余量取上限覆盖常见字号。
STROKE_OVERFLOW_MARGIN = 8

_DEFAULT_SOURCE = "photos"


def bbox_pad(box_source: str | None) -> int:
    """布局边界/擦字范围的扩边量。"""
    return BBOX_PAD.get(str(box_source or _DEFAULT_SOURCE), BBOX_PAD[_DEFAULT_SOURCE])


def glyph_margin(box_source: str | None) -> int:
    """字号上限相对框尺寸的余量。"""
    return GLYPH_MARGIN.get(
        str(box_source or _DEFAULT_SOURCE), GLYPH_MARGIN[_DEFAULT_SOURCE]
    )

# --- 岛级决策：几何规则 or 小分类器 -------------------------------------------
# 小分类器是**用我们自己的真值训出来的**（748 岛 / 63 页，见
# `manga_localizer/sfx_classifier.py` 与 开发记录 6c-2/6c-3）。实测（留一页 CV）：
#   几何：误杀台词 24 / 混入拟声 258（81%）
#   分类器 @0.4：误杀台词 **10** / 混入 278（87%）→ 台词误杀减半多，混入率 +6pp
# 阈值就是"保台词 ↔ 少混入"的旋钮：
#   0.2 → 误杀 1 / 混入 315 | 0.3 → 3 / 307 | 0.4 → 10 / 278 | 0.5 → 26 / 227 | 0.6 → 41 / 173
# 权重文件缺失 / 特征维度不符时**自动退回几何规则**（不因缺文件改变行为）。
ART_TEXT_DECISION = "classifier"      # "classifier" | "geometry"
# 分类器投票线：P(台词) 低于此值 = 分类器投"像拟声"一票。
# **2026-09-30 用户定稿"严格联合版"**（开发记录 六之前四）：
#   留日文 = (P < 此值 ∨ 框级软标记) ∧ 字数 < ART_TEXT_STRICT_MAX_CHARS
# 0.6 的依据（三本书 1542 岛留一书 CV）：成句台词（≥12 字）要到 P<0.7 才开始被
# 留日文（三本共 2 个），0.6 档被留的全是 ≤6 字假名短叹（えっ/うん 级，日文原样
# 无感）；部署权重回看 丙书 自己的 545 条清单可接管 57%。
# 历史：2026-09-16 曾定 0.1——当时口径是"丢 = 台词消失"，保守正确；后来把口径
# 修正为"丢 = 保留日文原样"（不擦不译不嵌，原文还在画面上），才敢抬到 0.6。
# 注：art_text_force_drop.txt（人工判定）不受此值影响；keep 清单照常救回。
# 另：CNN / stacking 同口径实测均未超过本特征模型（开发记录 6c-5），故不采用。
ART_TEXT_CLASSIFIER_THRESHOLD = 0.6

# --- 严格联合版（用户 2026-09-30 定）：框级软标记 + 字数护栏 -----------------
# 框级软标记 = 现行大拟音硬过滤（2.0×/10% 硬丢）的**放宽档，只标记不丢框**：
# 框和文本都留在数据集里，成岛后由岛级裁决（拿到 OCR 全文与分类器分数那一刻），
# 被标记的岛 ≥护栏字数就整岛救回、全文翻译（擦字覆盖全部成员框，无残墨断句）。
# 不丢框是救援的前提——丢了框，救回的岛就缺一段墨、断一句文。
# 实测（CV，1542 岛）：软标记贡献了严格版 453 个拦截里的 424 个；放宽档不配
# 岛级救援 = 111 个台词受伤（6c-3 的血案），救援是必需的。
ART_TEXT_SOFT_FLAG_RATIO = 1.2    # 短边 > 该倍数 × 同方向基准
